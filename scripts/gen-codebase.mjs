// Generates CODEBASE.md: every project source file, verbatim, in one document.
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { extname, join, relative } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const include = ['index.html', 'package.json', 'tsconfig.json', 'vite.config.ts', '.gitignore', 'scripts', 'src'];
const langs = { '.ts': 'ts', '.mjs': 'js', '.js': 'js', '.json': 'json', '.html': 'html', '.css': 'css', '.md': 'md' };

function walk(p, out) {
  const st = statSync(p);
  if (st.isDirectory()) {
    for (const name of readdirSync(p).sort()) walk(join(p, name), out);
  } else {
    out.push(p);
  }
  return out;
}

const files = include.flatMap((entry) => walk(join(root, entry), []));
const tree = files.map((f) => `- ${relative(root, f)}`).join('\n');
let lines = 0;
const body = files
  .map((f) => {
    const rel = relative(root, f);
    const src = readFileSync(f, 'utf8');
    lines += src.split('\n').length;
    const fence = src.includes('```') ? '````' : '```';
    return `## \`${rel}\`\n\n${fence}${langs[extname(f)] ?? ''}\n${src.replace(/\n$/, '')}\n${fence}\n`;
  })
  .join('\n');

const doc = `# MachZero — Complete Source\n\nGenerated by \`npm run codebase\`. ${files.length} files, ${lines} lines.\nSee \`docs/TDD.md\` for the architecture and \`README.md\` for commands.\n\n## File index\n\n${tree}\n\n${body}`;
writeFileSync(join(root, 'CODEBASE.md'), doc);
console.log(`CODEBASE.md written: ${files.length} files, ${lines} lines`);
