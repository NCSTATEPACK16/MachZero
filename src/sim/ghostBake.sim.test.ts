/**
 * Dev ghosts and dev times (IMPLEMENTATION §M8b step 4). `npm run ghosts:bake` (BAKE_GHOSTS=1) runs the solo dev
 * race on every track (a COMET with the Legend rivals' parts, variant A; a Legend autopilot, `steady`, seed 12345,
 * normal hazards), records its ghost, and writes `public/game/ghosts/<trackId>.bin` and `src/content/devTimes.ts`.
 *
 * Without BAKE_GHOSTS this file is the guard: a fresh dev run is within 0.5% of DEV_TIMES, and the committed ghost
 * decodes with the same total time. If it fails, the track or the physics changed: run `npm run ghosts:bake`.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import { DEV_TIMES } from '../content/devTimes';
import { TRACK_DEFS } from '../content/tracks';
import { GHOST_HZ, decodeGhost, encodeGhost } from '../game/ghost/ghostCodec';
import { devLoadout, soloRace } from './soloRace';

const ROOT = join(__dirname, '..', '..');
const GHOST_DIR = join(ROOT, 'public', 'game', 'ghosts');
const TRACK_IDS = Object.keys(TRACK_DEFS);
const BAKE = !!process.env.BAKE_GHOSTS;
/** A fresh run may differ from the committed time by this much (another CPU's floating point). */
const TOLERANCE = 0.005;

const bin = (id: string) => join(GHOST_DIR, `${id}.bin`);

function toArrayBuffer(b: Buffer): ArrayBuffer {
  return b.buffer.slice(b.byteOffset, b.byteOffset + b.byteLength) as ArrayBuffer;
}

describe.runIf(BAKE)('bake the dev ghosts', () => {
  it('records every track and writes the ghosts and devTimes.ts', { timeout: 600_000 }, async () => {
    mkdirSync(GHOST_DIR, { recursive: true });
    const times: Record<string, number> = {};
    for (const id of TRACK_IDS) {
      const r = await soloRace(id, devLoadout(), { ghost: true });
      expect(Number.isFinite(r.total), `${id}: the dev run finishes`).toBe(true);
      const buf = encodeGhost(r.ghost!);
      writeFileSync(bin(id), new Uint8Array(buf));
      times[id] = Math.round(r.total * 1000) / 1000;
      console.log(`${id}: ${r.total.toFixed(3)} s, ${r.ghost!.count} samples, ${(buf.byteLength / 1024).toFixed(1)} KB`);
    }
    const lines = TRACK_IDS.map((id) => `  '${id}': ${times[id]},`).join('\n');
    writeFileSync(
      join(ROOT, 'src', 'content', 'devTimes.ts'),
      `/**\n * Generated by \`npm run ghosts:bake\` (src/sim/ghostBake.sim.test.ts): do not edit. The dev ghost's 3-lap total time\n * (s) on each track: a COMET with the Legend rivals' parts, variant A, driven by a solo Legend autopilot. Time Trial\n * medals are measured against it (IMPLEMENTATION §M8b).\n */\nexport const DEV_TIMES: Readonly<Record<string, number>> = {\n${lines}\n};\n`,
    );
  });
});

describe.skipIf(BAKE)('dev ghosts guard', () => {
  it.each(TRACK_IDS)('%s: the committed dev time and ghost match a fresh dev run', { timeout: 60_000 }, async (id) => {
    const dev = DEV_TIMES[id];
    expect(dev, `${id} has a dev time: run npm run ghosts:bake`).toBeGreaterThan(0);
    expect(existsSync(bin(id)), `${id}.bin is committed: run npm run ghosts:bake`).toBe(true);
    const ghost = decodeGhost(toArrayBuffer(readFileSync(bin(id))));
    expect(ghost, `${id}.bin decodes`).not.toBeNull();
    expect(ghost!.trackId).toBe(id);
    expect(ghost!.chassisId).toBe('comet');
    expect(ghost!.totalTime).toBeCloseTo(dev, 2);
    // The ghost covers the whole run (20 Hz from GO to the line).
    expect(Math.abs((ghost!.count - 1) / GHOST_HZ - ghost!.totalTime)).toBeLessThan(0.1);
    const r = await soloRace(id, devLoadout());
    expect(Math.abs(r.total - dev) / dev, `${id}: a fresh dev run took ${r.total.toFixed(3)} s against ${dev} s: the track or the physics changed, run npm run ghosts:bake`).toBeLessThanOrEqual(TOLERANCE);
  });
});
